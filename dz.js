//1. 
console.log('number' + 3 + 3);

//Description
// 1) Оператор +, слева строка 'number', справа число 3 → выполняется конкатенация.
//    3 (три) приводится к строке '3'.
//    Получаем: 'number3' + 3
// 2) Снова +, слева строка 'number3', справа число 3 → конкатенация.
//    3 приводится к строке '3'.
//    Получаем: 'number33'
// Ответ: 'number33'

//2.
console.log(null + 3);

//Description
// 1) Оператор +, нет строк → идет численное сложение.
// 2) Number(null) → 0
// 3) 0 + 3 = 3
// Ответ: 3

//3.
console.log(5 && "qwerty");

//Description
// 1) Оператор && возвращает первый falsy или последний truthy.
// 2) 5 → truthy, значит проверяем второй операнд( аргумент операции, данные, которые обрабатываются командой, или математическое выражение, задающее значение аргумента операции.) 
// и возвращаем его.
// 3) Второй операнд "qwerty" → truthy, он и возвращается.
// Ответ: "qwerty"

//4.
console.log(+'40' + +'2' + "hillel");

//Description
// 1) Унарный плюс(это унарный оператор, который преобразует значение в число.): +'40' → Number('40') → 40
// 2) Унарный плюс: +'2' → Number('2') → 2
// 3) 40 + 2 = 42 (оба операнда числа)
// 4) 42 + "hillel" → есть строка → происходит конкатенация. 42 → "42"
// Ответ: "42hillel"

//5.
console.log('10' - 5 === 6);

//Description
// 1) Оператор - всегда приводит к числам.
//    '10' → Number('10') → 10
//     10 - 5 = 5
// 2) 5 === 6 → строгое сравнение (тип и значение).
//    5 и 6 — оба number, но значения разные → false
// Ответ: false (boolean)

//6.
console.log(true + false);

//Description
// 1) При сложении boolean приводятся к числам.
//    Number(true) → 1
//    Number(false) → 0
// 2) 1 + 0 = 1
// Ответ: 1 (number)

//7.
console.log('4px' - 3);

//Description
// 1) Оператор - требует числа → '4px' пытается преобразоваться в число.
// 2) Number('4px') → NaN (некорректный числовой формат).
// 3) NaN - 3 → NaN
// Ответ: NaN (number)

//8.
console.log('4' - 3);

//Description
// 1) '4' → Number('4') → 4
// 2) 4 - 3 = 1
// Ответ: 1 (number)

//9.
console.log('6' + 3 ** 0);

//Description
// 1) Оператор ** имеет более высокий приоритет, чем +.
//    3 ** 0 = 1
// 2) Получаем: '6' + 1
//    Есть строка → конкатенация.
//    1 → '1'
//    '6' + '1' = '61'
// Ответ: '61' (string)

//10.
console.log(12 / '6');

//Description
// 1) Оператор / → оба операнда приводятся к числам.
// 2) '6' → Number('6') → 6
// 3) 12 / 6 = 2
// Ответ: 2 (number)

//11.
console.log('10' + (5 === 6));

//Description
// 1) В скобках: 5 === 6 → сравнение двух чисел → false
// 2) '10' + false
//    Есть строка → конкатенация.
//    false → 'false'
//    '10' + 'false' = '10false'
// Ответ: '10false' (string)

//12.
console.log(null == '');

//Description
// 1) По правилам ==, null равен только null или undefined.
// 2) Сравнение null со строкой '' → всегда false, без приведения к числу.
// Ответ: false (boolean)

//13.
console.log(3 ** (9 / 3));

//Description
// 1) Сначала в скобках: 9 / 3 = 3
// 2) 3 ** 3 = 27
// Ответ: 27 (number)

//14.
console.log(!!'false' == !!'true');

//Description
// 1) 'false' — НЕ пустая строка → truthy.
//    !'false' → false
//    !!'false' → true
// 2) 'true' — тоже непустая строка → truthy.
//    !'true' → false
//    !!'true' → true
// 3) true == true → оба boolean, нестрогое сравнение → true
// Ответ: true (boolean)

//15.
console.log(0 || '0' && 1);

//Description
// 1) Оператор && имеет более высокий приоритет, чем ||.
//    Сначала считаем: '0' && 1
//    '0' → непустая строка → truthy, значит && возвращает второй операнд → 1
// 2) Получаем: 0 || 1
//    0 → falsy, || возвращает первый truthy → 1
// Ответ: 1 (number)

//16.
console.log((+null == false) < 1);

//Description
// 1) +null(Унарный плюс приобразовывает значение в число) → Number(null) → 0
// 2) 0 == false
//    При == boolean приводится к числу: Number(false) → 0
//    0 == 0 → true
// 3) Выражение в скобках стало true.
// 4) true < 1
//    При сравнении < оба операнда приводятся к числам.
//    Number(true) → 1
//    Получаем: 1 < 1 → false
// Ответ: false (boolean)

//17.
console.log(false && true || true);

//Description
// 1) Сначала && (высший приоритет).
//Если A falsy → сразу возвращает A (второй операнд даже не вычисляется) Если A truthy → возвращает B
//    false && true → первый операнд falsy, результат → false.
//Если A truthy → возвращает A Если A falsy → возвращает B
// 2) Далее false || true
//    false → falsy, || возвращает первый truthy → true
// Ответ: true (boolean)

//18.
console.log(false && (false || true));

//Description
// 1) В скобках: false || true
//    || возвращает первый truthy → true
// 2) false && true
//    Первый операнд falsy → результат false (короткое замыкание).
// Ответ: false (boolean)

//19.
console.log((+null == false) < 1 ** 5);

//Description
// 1) Оператор ** имеет более высокий приоритет, чем <.
//    1 ** 5 = 1
// 2) Левая часть: +null == false (0 == false)
//    +null → 0
//    0 == false → Number(false) → 0 → 0 == 0 → true
// 3) Имеем: true < 1
//    true → Number(true) → 1
//    1 < 1 → false
// Ответ: false (boolean)